#!/usr/bin/env python3
"""Generates the app's `rune::Icon` statics.

- `src/icons.rs`: the Lucide icons named in `tools/icons.txt`, read from gpui-kit-assets'
  copy of the Lucide catalog (`~/.cargo/registry/src/*/gpui-kit-assets-0.8.1/assets/icons`,
  or the directory given as the first argument).
- `src/logos/marks.rs`: every provider logo in `assets/logos/*.svg`.

A Rune icon body is the elements inside a square viewBox (`rune::Icon { name, view, body }`), so
each SVG's root paint attributes (fill, stroke, widths, caps, joins, fill rule) move onto a
`<g>` wrapping its children. Black fills in the Lucide set become `currentColor` so they tint
like the rest. Run from anywhere: `python3 crates/j3-desktop/tools/gen_icons.py`.
"""

import glob
import os
import re
import sys

CRATE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAINT = ["fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "fill-rule"]
NAMED_COLORS = {"gold": "#FFD700"}


def lucide_dir():
    if len(sys.argv) > 1:
        return sys.argv[1]
    found = glob.glob(os.path.expanduser("~/.cargo/registry/src/*/gpui-kit-assets-0.8.1/assets/icons"))
    if not found:
        sys.exit("gpui-kit-assets-0.8.1 is not in the cargo registry; pass its assets/icons directory")
    return found[0]


def body_of(svg, lucide):
    """(view, body) of an SVG document as a Rune icon."""
    root = re.search(r"<svg\b([^>]*)>", svg, re.S)
    if not root:
        raise ValueError("no <svg> root")
    attrs = dict(re.findall(r'([\w:-]+)="([^"]*)"', root.group(1)))
    view = attrs.get("viewBox", "0 0 24 24").split()
    if view[0] != "0" or view[1] != "0" or view[2] != view[3]:
        raise ValueError(f"viewBox {view} is not square at the origin")
    inner = svg[root.end():svg.rindex("</svg>")]
    inner = re.sub(r"<title>.*?</title>", "", inner, flags=re.S)
    inner = re.sub(r"<!--.*?-->", "", inner, flags=re.S)
    inner = re.sub(r'\s(class|id|version)="[^"]*"', "", inner) if lucide else inner
    for name, hex_ in NAMED_COLORS.items():
        inner = inner.replace(f'="{name}"', f'="{hex_}"')
    if lucide:
        inner = re.sub(r'(fill|stroke)="#000(000)?"', r'\1="currentColor"', inner)
    inner = re.sub(r">\s+<", "><", inner).strip()
    inner = re.sub(r"\s+", " ", inner)
    paint = " ".join(f'{k}="{attrs[k]}"' for k in PAINT if k in attrs)
    body = f"<g {paint}>{inner}</g>" if paint else inner
    return view[2], body


def rust_str(s):
    hashes = "#"
    while f'"{hashes}' in s:
        hashes += "#"
    return f'r{hashes}"{s}"{hashes}'


def const_name(stem):
    return re.sub(r"[^A-Za-z0-9]", "_", stem).upper()


def write(path, header, entries):
    lines = [header, "", "use rune::Icon;", ""]
    for name, stem, view, body in entries:
        lines.append(f"pub static {name}: Icon = Icon {{")
        lines.append(f'    name: "{stem}",')
        lines.append(f"    view: {float(view)},")
        lines.append(f"    body: {rust_str(body)},")
        lines.append("};")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    src = lucide_dir()
    with open(os.path.join(CRATE, "tools/icons.txt")) as f:
        names = sorted({line.strip() for line in f if line.strip() and not line.startswith("#")})
    entries = []
    for stem in names:
        with open(os.path.join(src, f"{stem}.svg")) as f:
            view, body = body_of(f.read(), lucide=True)
        entries.append((const_name(stem), stem, view, body))
    write(
        os.path.join(CRATE, "src/icons.rs"),
        "//! Lucide icons (ISC licence, see NOTICE) the app draws, as `rune::Icon`s.\n"
        "//! Generated by `tools/gen_icons.py` from `tools/icons.txt`; do not edit. To add one, list\n"
        "//! its Lucide name in `tools/icons.txt` and rerun the script.",
        entries,
    )
    logos = []
    for path in sorted(glob.glob(os.path.join(CRATE, "assets/logos/*.svg"))):
        stem = os.path.basename(path)[:-4]
        with open(path) as f:
            view, body = body_of(f.read(), lucide=False)
        logos.append((const_name(stem), stem, view, body))
    write(
        os.path.join(CRATE, "src/logos/marks.rs"),
        "//! Provider logos from `assets/logos/` as `rune::Icon`s; coloured ones draw in their own\n"
        "//! colours. Generated by `tools/gen_icons.py`; do not edit.",
        logos,
    )
    print(f"{len(entries)} icons, {len(logos)} logos")


main()
